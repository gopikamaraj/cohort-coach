"""Cost per teacher per 3-week track, in US cents, from measured call costs and assumptions.

Usage: python scripts/cost_per_teacher.py [--out docs/evidence]
Reads the live calls in the audit table (the mean cost of each call), applies
docs/evidence/cost_assumptions.yaml, and writes cost_per_teacher.json and .md with a low to high
range and a breakdown by call. No number is typed by hand: change the assumptions and re-run.
Speech (Sarvam) is priced separately in services/speech/pricing.yaml and is not in this figure.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

ASSUMPTIONS = ROOT / "docs" / "evidence" / "cost_assumptions.yaml"
# which call each activity causes: activity -> (call key, model filter or None)
CALLS = {
    "check_sheets": ("c08_answer_reading", None),
    "child_lines": ("c01_child_voice", "claude-sonnet-5-5"),
    "move_labels": ("c02_move_label", None),
    "checks": ("c07_checker", None),
    "feedback": ("c03_feedback", None),
    "drafting": ("c05_track_draft", None),
}


def estimate(means: dict[str, float], a: dict[str, Any]) -> dict[str, Any]:
    """Cents per teacher per track at the low and high ends, by activity. Pure and tested."""
    pt, dr = a["per_teacher_per_track"], a["drafting"]
    out: dict[str, Any] = {"low": {}, "high": {}}
    for end in ("low", "high"):
        sessions = pt["practice_sessions"][end]
        turns = sessions * pt["turns_per_session"][end]
        cost = {
            "check_sheets": pt["sheets_read"][end] * means.get("check_sheets", 0.0),
            "child_lines": turns * means.get("child_lines", 0.0),
            "move_labels": turns * means.get("move_labels", 0.0),
            # a check on every child line and every feedback card
            "checks": (turns + sessions * pt["feedback_per_session"][end])
            * means.get("checks", 0.0),
            "feedback": sessions * pt["feedback_per_session"][end] * means.get("feedback", 0.0),
        }
        # drafting is shared by a cohort: the most costly case is few teachers and two languages
        langs = dr["languages"]["high" if end == "high" else "low"]
        size = dr["cohort_size"]["low" if end == "high" else "high"]
        parts = dr["parts_per_language"] * langs
        draft = parts * (
            means.get("drafting", 0.0) + dr["checks_per_part"] * means.get("checks", 0.0)
        )
        cost["drafting"] = draft / size
        out[end] = {k: round(v * 100, 3) for k, v in cost.items()}  # US cents
        out[end]["total"] = round(sum(out[end].values()), 3)
    return out


def measured_means() -> tuple[dict[str, float], dict[str, int]]:
    from ai import config

    config.load_env()
    from sqlalchemy import select
    from sqlalchemy.orm import sessionmaker

    from services.api.db import AiCall, make_engine

    db = sessionmaker(make_engine(), expire_on_commit=False)()
    rows = list(db.execute(select(AiCall).where(AiCall.mode.in_(("live", "record")))).scalars())
    means: dict[str, float] = {}
    counts: dict[str, int] = {}
    for activity, (key, model) in CALLS.items():
        costs = [
            r.cost_usd for r in rows if r.call_key == key and (model is None or r.model == model)
        ]
        counts[activity] = len(costs)
        if costs:
            means[activity] = sum(costs) / len(costs)
    return means, counts


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--out", default=str(ROOT / "docs" / "evidence"))
    args = p.parse_args(argv)
    assumptions = yaml.safe_load(ASSUMPTIONS.read_text(encoding="utf-8"))
    means, counts = measured_means()
    result = estimate(means, assumptions)
    doc = {
        "unit": "US cents per teacher per 3-week track",
        "measured_mean_usd_per_call": {k: round(v, 6) for k, v in means.items()},
        "live_calls_measured": counts,
        "assumptions": "docs/evidence/cost_assumptions.yaml",
        "range": result,
        "not_included": "speech (services/speech/pricing.yaml), hosting",
    }
    out = Path(args.out)
    (out / "cost_per_teacher.json").write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
    lines = [
        "# Cost per teacher per track",
        "",
        "Generated by `python scripts/cost_per_teacher.py` from the audit table and",
        "`docs/evidence/cost_assumptions.yaml`. Per-call costs are measured; calls per",
        "teacher are an assumption. US cents; speech and hosting are not included.",
        "",
        "| Activity | Low (cents) | High (cents) | Measured calls behind the mean |",
        "| --- | --- | --- | --- |",
    ]
    for k in (
        "check_sheets",
        "child_lines",
        "move_labels",
        "checks",
        "feedback",
        "drafting",
        "total",
    ):
        label, lo, hi = k.replace("_", " "), result["low"][k], result["high"][k]
        lines.append(f"| {label} | {lo} | {hi} | {counts.get(k, '')} |")
    (out / "cost_per_teacher.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
