"""docs/evidence/demo_synthetic_reading.md: the demo's AI reading on SYNTHETIC sheets, and the
measured time and AI cost of one demo run.

    python scripts/demo_evidence.py --live [--run-db e2e-record.sqlite]

--live   reads every demo sheet of the scenario with the real reader (call 8; Haiku, Sonnet on a
         retry). It prints a cost estimate first. Without --live the reading part is left as
         "not run" (no number is ever written by hand).
--run-db the database of a demo run made in record mode (AI_MODE=record): the AI cost of one full
         demo run is the sum over its distinct calls (each call once, as on a cold cache).
The run time comes from apps/pwa/test-results/demo-run.json, which the end-to-end test writes.

Synthetic sheets only: the handwriting is fonts, drawn by code. This is not evidence of how well
the reader does on real children's handwriting.
"""

from __future__ import annotations

import argparse
import json
import sqlite3
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

OUT = ROOT / "docs" / "evidence" / "demo_synthetic_reading.md"
RUN_JSON = ROOT / "apps" / "pwa" / "test-results" / "demo-run.json"
EST_PER_SHEET_USD = 0.002  # Haiku read, plus a Sonnet retry on some sheets (ai/pricing.yaml)


def read_all() -> dict[str, Any]:
    from ai.calls.c08_answer_reading import read_sheet
    from ai.client import CallContext
    from services.demo import scenario as sc
    from services.demo import sheets
    from services.demo.api import CACHE, _model_image
    from services.papers import generator as g
    from services.papers.rules import seed_rules

    rules = seed_rules()
    s = sc.load_scenario()
    demo = sc.build_class(s)
    paper = g.pilot_paper(g.CheckRef("demo:1", "pre", "A", demo.class_code, 1), rules, 1, "A")
    folder = CACHE / f"{demo.scenario}-{demo.seed}-{paper.hash[:12]}"
    paths = sheets.render_sheets(demo, paper.to_dict(), rules, folder)
    print(f"{len(paths)} sheets; estimated AI cost about ${EST_PER_SHEET_USD * len(paths):.2f}")
    rows = []
    cost = 0.0
    for child, path in zip(demo.children, paths, strict=True):
        b64, media = _model_image(path.read_bytes())
        out = read_sheet(b64, media, demo.form, context=CallContext(mode="live"))
        cost += sum(r.cost_usd for r in out.runs) if out else 0.0
        cells = [] if out is None else [(c.text, c.status) for c in out.cells]
        truth = list(child.answers)
        right = sum(
            1
            for (text, status), want in zip(cells, truth, strict=False)
            if ("" if status == "blank" else text) == want
        )
        auto = [
            (text, status, want)
            for (text, status), want in zip(cells, truth, strict=False)
            if status == "ok"
        ]
        rows.append(
            {
                "sheet": path.name,
                "hard": child.hard or "",
                "boxes": len(truth),
                "right": right,
                "auto": len(auto),
                "auto_right": sum(1 for text, _, want in auto if text == want),
                "flagged": sum(1 for _, status in cells if status == "check"),
                "read": out is not None,
            }
        )
    return {"rows": rows, "cost": cost}


def run_cost(db: Path) -> dict[str, Any] | None:
    if not db.exists():
        return None
    con = sqlite3.connect(db)
    seen: dict[str, tuple[str, float]] = {}
    for key, digest, cost in con.execute(
        "select call_key, input_hash, cost_usd from ai_calls where mode = 'record' order by id"
    ):
        seen.setdefault(digest, (key, float(cost or 0)))
    by_call: dict[str, float] = {}
    for key, cost in seen.values():
        by_call[key] = by_call.get(key, 0.0) + cost
    return {"calls": len(seen), "usd": sum(by_call.values()), "by_call": by_call}


def write(reading: dict[str, Any] | None, cost: dict[str, Any] | None) -> None:
    lines = [
        "# Demo flow: AI reading on synthetic sheets, and one run's time and cost",
        "",
        "Generated by `scripts/demo_evidence.py`. Do not edit by hand.",
        "",
        "**Synthetic sheets.** The 20 demo sheets are drawn by code (handwriting-style fonts, a "
        "simulated phone photo) from the demo scenario (`demo/scenarios/class_3a.yaml`). This is "
        "not evidence of how the reader does on real children's handwriting: that is measured on "
        "the hand-keyed set (`evals/results.md`).",
        "",
        "## AI reads of the demo sheets",
        "",
    ]
    if reading is None:
        lines += ["Not run yet: `python scripts/demo_evidence.py --live` reads them.", ""]
    else:
        rows = reading["rows"]
        boxes = sum(r["boxes"] for r in rows)
        right = sum(r["right"] for r in rows)
        auto = sum(r["auto"] for r in rows)
        auto_right = sum(r["auto_right"] for r in rows)
        flagged = sum(r["flagged"] for r in rows)
        lines += [
            f"{len(rows)} sheets, {boxes} boxes, read by call 8 (no expected answer shown to it). "
            f"{right} of {boxes} boxes read as the code drew them. {auto} boxes were accepted "
            f"without a check, and {auto_right} of those were right; {flagged} boxes were sent "
            f"to the teacher to check. AI cost of these reads: ${reading['cost']:.4f}.",
            "",
            "| Sheet | Hard case | Boxes right | Accepted without a check (right) "
            "| Sent to check |",
            "| --- | --- | --- | --- | --- |",
        ]
        for r in rows:
            lines.append(
                f"| {r['sheet']} | {r['hard'] or '—'} | {r['right']} of {r['boxes']} | "
                f"{r['auto']} ({r['auto_right']}) | {r['flagged']} |"
            )
        lines.append("")
    lines += ["## One demo run", ""]
    run = json.loads(RUN_JSON.read_text(encoding="utf-8")) if RUN_JSON.exists() else None
    if run:
        lines.append(
            f"The automated end-to-end run (`apps/pwa/e2e/demo.spec.ts`, all {run['steps']} steps, "
            f"recorded AI answers) took {run['seconds']} seconds on {run['at'][:10]}. A person "
            "reading each screen takes longer; that has not been timed yet."
        )
    else:
        lines.append("Run time: not measured yet (run `npm run e2e -- demo`).")
    lines.append("")
    if cost:
        parts = ", ".join(f"{k} ${v:.4f}" for k, v in sorted(cost["by_call"].items()))
        lines.append(
            f"AI cost of one full demo run with nothing cached: ${cost['usd']:.4f} over "
            f"{cost['calls']} distinct calls ({parts}), from a run in record mode. Later runs "
            "reuse the cached sheet read and the cached first lesson."
        )
    else:
        lines.append("AI cost of a run: not measured yet (needs a run in record mode).")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--live", action="store_true")
    ap.add_argument("--run-db", default=str(ROOT / "e2e-record.sqlite"))
    a = ap.parse_args(argv)
    from ai.config import load_env

    load_env()
    reading = read_all() if a.live else None
    write(reading, run_cost(Path(a.run_db)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
