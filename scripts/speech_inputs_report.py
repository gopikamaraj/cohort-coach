"""Write docs/build/reports/SPEECH-INPUTS.md: the input built for the speech call for every module in every
language, its hash and length, and a lint table of every digit number with whether the sidecar marks it
and the sentence around it, so a content owner can decide. No network, no AI call.

    python scripts/speech_inputs_report.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from services.modules import library, speech_input  # noqa: E402
from services.modules.speech_input import SpeechInputError, build_speech_input  # noqa: E402

OUT = ROOT / "docs" / "build" / "reports" / "SPEECH-INPUTS.md"
ERRORS = ("PV-HEARD", "ADD-NOCARRY", "SUB-SFL", "SUB-NODEC")


def main() -> int:
    lines = ["# Speech inputs report", "", "Generated by `scripts/speech_inputs_report.py`. No AI or network call. Each module is built as module 1 of 3; the first one is also shown with no number and count.", ""]
    lint: list[tuple[str, str, str, bool, str]] = []
    longest = 0
    first = True
    for error in ERRORS:
        for approach in library.plan_for(error).approaches():
            for lang in ("en", "hi", "ta"):
                mt = library.module_text(error, approach, False, lang)
                if mt.omitted and "all" in mt.omitted:
                    continue
                d = mt.to_dict()
                readings = speech_input.readings_for(d)
                try:
                    si = build_speech_input(d, language=lang, number=1, count=3, digit_readings=readings, prompt_version=2, model="report")
                except SpeechInputError as exc:
                    lines += [f"## {error}:{approach} ({lang})", "", f"Not built: {exc}", ""]
                    continue
                longest = max(longest, len(si.text))
                lines += [f"## {error}:{approach} ({lang})", "", f"hash `{si.input_hash[:16]}`, {len(si.text)} characters, facts `{si.facts}`", "", "```text", si.text, "```", ""]
                if first:
                    bare = build_speech_input(d, language=lang, digit_readings=readings, prompt_version=2, model="report")
                    lines += ["Without number and count:", "", "```text", bare.text.split("<module>")[0].strip(), "```", ""]
                    first = False
                for s in si.sections:
                    for m in re.finditer(r"\{digits:(\d+)\}|(?<![\w{:])(\d+)(?![\w}])", s.lines()):
                        sentence = next((x for x in re.split(r"(?<=[.?!])\s+", s.lines()) if m.group(0) in x), "")
                        lint.append((f"{error}:{approach} ({lang})", s.tag, m.group(1) or m.group(2), m.group(1) is not None, sentence.strip()))
    lines += ["## Digit numbers", "", "| Module | Section | Number | Read digit by digit | Sentence |", "| --- | --- | --- | --- | --- |"]
    lines += [f"| {m} | {t} | {n} | {'yes' if marked else 'no'} | {sent.replace('|', '/')} |" for m, t, n, marked, sent in lint]
    unmarked = sum(1 for x in lint if not x[3])
    lines += ["", f"{len(lint)} digit numbers, {len(lint) - unmarked} marked, {unmarked} unmarked (read as ordinary numbers).", "", f"Longest input: {longest} characters (limit {speech_input.MAX_INPUT_CHARS}).", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(lint)} digit numbers, {unmarked} unmarked, longest {longest} characters")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
