"""Translator workflow for the PWA strings: export to one CSV, import it back, list what is missing.

Usage:
  python scripts/i18n.py export [out.csv]  key, en, hi, ta per string (default docs/build/i18n.csv)
  python scripts/i18n.py import in.csv     write hi, ta and en back into apps/pwa/src/i18n/*.json
  python scripts/i18n.py todo [--check]    list keys missing or empty in hi or ta in i18n-todo.md

English is the source of truth; a key with no Hindi or Tamil falls back to English in the app and
shows up in the to-do list.
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
I18N = ROOT / "apps" / "pwa" / "src" / "i18n"
TODO = ROOT / "docs" / "build" / "i18n-todo.md"
LANGS = ("en", "hi", "ta")
HEADER = """# i18n to-do

Missing `ta` / `hi` translations (they fall back to English). Every user-facing string needs
`en`, `hi` and `ta`. Generated by `python scripts/i18n.py todo`. The build's first-draft Hindi and
Tamil wording is marked for native review in `docs/build/PROGRESS.md`.

| Key | Missing in | Added in phase | Owner |
| --- | --- | --- | --- |
"""


def load() -> dict[str, dict[str, str]]:
    return {lang: json.loads((I18N / f"{lang}.json").read_text(encoding="utf-8")) for lang in LANGS}


def export(path: Path) -> int:
    tables = load()
    with path.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["key", *LANGS])
        for key in tables["en"]:
            w.writerow([key, *(tables[lang].get(key, "") for lang in LANGS)])
    print(f"wrote {path} ({len(tables['en'])} strings)")
    return 0


def import_csv(path: Path) -> int:
    tables = load()
    with path.open(encoding="utf-8-sig", newline="") as f:
        for row in csv.DictReader(f):
            key = row["key"]
            if key not in tables["en"]:
                print(f"unknown key, skipped: {key}")
                continue
            for lang in LANGS:
                if row.get(lang):
                    tables[lang][key] = row[lang]
    for lang in LANGS:
        (I18N / f"{lang}.json").write_text(
            json.dumps(tables[lang], ensure_ascii=False, indent=2) + "\n",
            encoding="utf-8",
            newline="\n",
        )
    print("imported; run the PWA tests to check key parity")
    return 0


def todo_text() -> str:
    tables = load()
    lines = [HEADER.rstrip("\n")]
    for key in tables["en"]:
        missing = [lang for lang in ("hi", "ta") if not tables[lang].get(key)]
        if missing:
            owner = "Shivani" if "hi" in missing else "Gopi"
            lines.append(f"| `{key}` | {', '.join(missing)} | P05 | {owner} |")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    cmd = argv[0] if argv else ""
    if cmd == "export":
        return export(Path(argv[1]) if len(argv) > 1 else ROOT / "docs" / "build" / "i18n.csv")
    if cmd == "import" and len(argv) > 1:
        return import_csv(Path(argv[1]))
    if cmd == "todo":
        text = todo_text()
        if "--check" in argv:
            same = TODO.exists() and TODO.read_text(encoding="utf-8").replace("\r\n", "\n") == text
            print("ok    docs/build/i18n-todo.md" if same else "STALE docs/build/i18n-todo.md")
            return 0 if same else 1
        TODO.write_text(text, encoding="utf-8", newline="\n")
        print("wrote docs/build/i18n-todo.md")
        return 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
