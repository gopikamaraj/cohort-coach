"""Scores every web app route against the browser QA rubric (docs/qa-rubric.md).

Reads two files written by real browser runs and writes docs/evidence/browser_qa.md; no score is
typed by hand. Inputs (both in docs/evidence/browser_qa/):
  report.json   from `node apps/pwa/qa/crawl.mjs docs/evidence/browser_qa` (every route, 3 languages,
                phone and desktop widths, against a running build and API)
  e2e_list.txt  from `npx playwright test --reporter=list` (the feature tests)
"""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DIR = ROOT / "docs" / "evidence" / "browser_qa"

# Which feature specs exercise each route (found by searching the specs for the route).
SPECS: dict[str, list[str]] = {
    "roles": ["landing", "tour"],
    "judge": ["app", "programme", "profile"],
    "home": ["app", "layout", "programme"],
    "check": ["check", "photo", "stages", "app"],
    "cards": ["app", "profile"],
    "practice": ["practice", "hints", "voice", "review"],
    "programme": ["programme", "profile"],
    "history": ["profile", "programme"],
    "aimap": ["practice", "hints"],
    "audit": ["practice", "review-queue"],
    "profile": ["profile", "app", "layout"],
    "privacy": [],
    "admin": ["pilot"],
    "coach": ["programme", "pilot"],
    "mentor": [],
    "flow": [],
    "officer": ["officer"],
    "watch": ["watch"],
    "tour": ["tour"],
    "tour/2": ["tour"],
    "review": ["review-queue", "review"],
    "cohort": ["cohort"],
}


def main() -> None:
    rows = json.loads((DIR / "report.json").read_text(encoding="utf-8"))
    listing = (DIR / "e2e_list.txt").read_text(encoding="utf-8", errors="replace")
    ok: Counter[str] = Counter()
    for m in re.finditer(r"^\s+ok\s+\d+\s+e2e[\\/]([\w-]+)\.spec\.ts", listing, re.M):
        ok[m.group(1)] += 1
    skipped = re.search(r"(\d+) skipped", listing)
    summary = re.search(r"(\d+) passed", listing)
    failed = re.search(r"(\d+) failed", listing)

    out = [
        "# Browser QA results",
        "",
        "Generated by `scripts/browser_qa_report.py`; do not edit by hand.",
        "",
    ]
    out.append(
        f"Feature tests (Playwright, real API in recorded and stub mode): {summary.group(1) if summary else '?'} passed, "
        f"{failed.group(1) if failed else '0'} failed, {skipped.group(1) if skipped else '0'} skipped (the screenshot-capture specs)."
    )
    out.append(f"Crawl: {len(rows)} page views, {sum(1 for r in rows if r['issues'])} with issues.")
    out += [
        "",
        "| Route | Loads clean (0-2) | Languages (0-2) | Layout and touch (0-2) | Browser feature test (0-2) | Rules (0-2) | Total /10 | Band |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    bands: Counter[str] = Counter()
    for route, specs in SPECS.items():
        rs = [r for r in rows if r["route"] == route]

        # 2 = clean at all 6 views, 1 = clean at 4 or 5, 0 = otherwise
        def sc(sub: list[dict], bad: tuple[str, ...]) -> int:  # type: ignore[type-arg]
            fails = sum(1 for r in sub if any(i.startswith(bad) for i in r["issues"]))
            return 2 if fails == 0 else 1 if fails <= 1 else 0

        loads = sc(rs, ("blank", "crawl failed", "console/page errors", "bad API", "undefined"))
        langs = (
            sc([r for r in rs if r["lang"] != "en"], ("raw string key", "blank", "crawl failed"))
            if rs
            else 0
        )
        layout = sc(rs, ("horizontal scroll", "tap targets"))
        n = sum(ok[s] for s in specs)
        feature = 0 if not specs else 2 if n >= 2 else 1
        rules = sc(rs, ("percentage",))
        total = loads + langs + layout + feature + rules
        band = "Pass" if total >= 9 else "Partial" if total >= 6 else "Gap"
        bands[band] += 1
        label = ", ".join(f"{s} ({ok[s]})" for s in specs) or "none"
        out.append(
            f"| #/{route} | {loads} | {langs} | {layout} | {feature} ({label}) | {rules} | {total} | {band} |"
        )
    out += ["", f"Bands: {dict(bands)}. Pass 9 to 10, Partial 6 to 8, Gap 5 or less.", ""]
    out.append(
        "Routes with no browser feature test are a gap in browser coverage, not a failure: the flows behind `#/flow` are covered by the golden-transcript tests through every adapter (`tests/channels/`)."
    )
    (ROOT / "docs" / "evidence" / "browser_qa.md").write_text(
        "\n".join(out) + "\n", encoding="utf-8"
    )
    print("\n".join(out))


if __name__ == "__main__":
    main()
