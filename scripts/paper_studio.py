"""Paper Studio files for judges. No AI is called.

python scripts/paper_studio.py rules      rules/paper-rules.v1.yaml (the seeded rule set)
python scripts/paper_studio.py samples    docs/samples/: a sample pre-test and its post-test
                                          twin in English, Hindi, Tamil and English + Hindi,
                                          with answer keys and layout maps (class "SAMPLE")
python scripts/paper_studio.py evidence   docs/evidence/paper_studio_verification.md: 200
                                          papers per language across the blueprints, each with
                                          its twin, through every automatic check; counts only
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from services.papers import generator as g  # noqa: E402
from services.papers import render, verifier  # noqa: E402
from services.papers.rules import LAYOUTS, seed_rules, to_yaml  # noqa: E402

RULES = seed_rules()
PER_LANGUAGE = 200


def write_rules() -> None:
    out = ROOT / "rules" / "paper-rules.v1.yaml"
    out.parent.mkdir(exist_ok=True)
    head = (
        "# Paper Studio rules, version 1 (seeded from engine/bugs.py and the pilot test pack).\n"
        "# Generated by scripts/paper_studio.py rules. A change is made as a new version in the\n"
        "# app (import this file as a draft); a second person publishes it.\n"
    )
    out.write_text(head + to_yaml(RULES), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


def write_samples() -> None:
    out = ROOT / "docs" / "samples"
    out.mkdir(parents=True, exist_ok=True)
    pre = g.CheckRef("sample:1", "pre", "A", "SAMPLE", 1)
    post = g.CheckRef("sample:1#post", "post", "B", "SAMPLE", 2)
    prof = g.profile_from_counts({"SUB-SFL": 9, "ADD-NOCARRY": 3}, 18, "en")
    a = g.generate_paper(pre, prof, RULES, "standard_10_5", 1, "sample")
    b = g.make_twin(a, RULES, post, "sample#post")
    for paper in (a, b):
        d = paper.to_dict()
        for lang in LAYOUTS:
            stem = f"SAMPLE-{paper.form}-{paper.kind}-{lang}"
            pdf, layout_map = render.render_paper(d, RULES, lang)
            (out / f"{stem}.pdf").write_bytes(pdf)
            (out / f"{stem}.layout.json").write_text(
                json.dumps(layout_map, indent=1, ensure_ascii=False) + "\n", encoding="utf-8"
            )
            (out / f"{stem}-key.pdf").write_bytes(render.render_key(d, RULES, lang))
    print(f"wrote {len(list(out.glob('SAMPLE-*')))} files to {out.relative_to(ROOT)}")


def _profiles() -> list[g.Profile]:
    return [
        g.baseline_profile("en"),
        g.profile_from_counts({"SUB-SFL": 9, "ADD-NOCARRY": 3}, 18, "en"),
        g.profile_from_counts({"PV-HEARD": 12, "PV-REVERSE": 4}, 25, "en"),
        g.profile_from_counts({"ADD-NOCARRY": 7, "SUB-NODEC": 6}, 30, "en"),
        g.profile_from_intake(["C2"], ["C1", "C2"], "en", 28),
        g.profile_from_intake(["C3"], ["C1", "C3"], "en", 20),
    ]


def write_evidence() -> None:
    profiles = _profiles()
    rows: list[tuple[str, int, int, Counter[str]]] = []
    for lang in LAYOUTS:
        packs = {
            p.lang: p.strings for p in RULES.string_packs if p.lang in render.LAYOUT_LANGS[lang]
        }
        string_findings = verifier.verify_strings(packs, verifier.FONTS)
        passed, made = 0, 0
        rules_failed: Counter[str] = Counter()
        for i in range(PER_LANGUAGE):
            bp = ("baseline_10", "standard_10_5")[i % 2]
            prof = profiles[i % len(profiles)]
            pre = g.CheckRef(f"ev-{i}:1", "pre", "A", "EVID", 1)
            post = g.CheckRef(f"ev-{i}:1#post", "post", "B", "EVID", 2)
            try:
                a = g.generate_paper(pre, prof, RULES, bp, 1, f"evidence-{i}")
                b = g.make_twin(a, RULES, post, f"evidence-{i}#post")
            except g.CannotMeet as exc:
                rules_failed[exc.rule] += 1
                continue
            made += 1
            found = list(string_findings)
            found += verifier.verify_items(a.to_dict())
            found += verifier.verify_items(b.to_dict(), twin_source=a.to_dict())
            for paper in (a, b):
                found += verifier.verify_layout(
                    render.render_paper(paper.to_dict(), RULES, lang)[1]
                )
            if found:
                rules_failed.update(f.rule for f in found)
            else:
                passed += 1
        rows.append((lang, made, passed, rules_failed))
        print(lang, made, passed, dict(rules_failed))
    names = {"en": "English", "hi": "Hindi", "ta": "Tamil", "en_hi": "English and Hindi"}
    lines = [
        "# Paper Studio: verification of generated papers",
        "",
        "Generated by `scripts/paper_studio.py evidence`. Do not edit by hand.",
        "",
        f"For each language layout, {PER_LANGUAGE} pre-tests were generated from rules version 1 "
        "(half on `baseline_10`, half on `standard_10_5`, across six class profiles from past "
        "counts, intake answers and the standard paper), each with its post-test twin. Every "
        "pre-test and twin went through the independent verifier (`services/papers/verifier.py`: "
        "keys, wrong answers, coverage, discrimination, duplicates, twins), the string and glyph "
        "check, and a full render whose layout map was checked for overflow and overlap. A pair "
        "passes only if both papers pass every check. These are generated papers with made-up "
        "class profiles, not real classes.",
        "",
        "| Layout | Pairs generated | Pairs that passed every check | Failed checks |",
        "| --- | --- | --- | --- |",
    ]
    for lang, made, passed, failed in rows:
        fails = ", ".join(f"{k}: {v}" for k, v in sorted(failed.items())) or "none"
        lines.append(f"| {names[lang]} | {made} of {PER_LANGUAGE} | {passed} of {made} | {fails} |")
    lines += [
        "",
        "Passing the automatic checks is not the same as approval of the wording: the Hindi "
        "and Tamil string packs are not yet reviewed by a reader of each language, so papers in "
        "those layouts wait in the review queue until a person approves them.",
        "",
    ]
    out = ROOT / "docs" / "evidence" / "paper_studio_verification.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    what = sys.argv[1] if len(sys.argv) > 1 else ""
    {"rules": write_rules, "samples": write_samples, "evidence": write_evidence}.get(
        what, lambda: print(__doc__)
    )()
