"""Write docs/evidence/pilot_results.md: children flagged before and after, counts only.

    python scripts/pilot_results.py              no pair yet: the "awaiting data" page
    python scripts/pilot_results.py BACKUP.json [--class ID] [--pre ID --post ID]

BACKUP.json is an unsealed export from the app's My profile. It holds per-child answers, so it
stays on the coordinator's machine and never enters git. The pair defaults to the class's latest
pre-test and the first post-test after it. Pairing runs here, by roll order, with
engine.checkpair; the page holds the two check labels, the number paired and left out, and counts
per competency. No row, roll number or name is written. It is labelled a small pilot, and a pair
under 10 children says the sample is small.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from engine.checkpair import COMPETENCIES, Pairing, pair_checks  # noqa: E402
from engine.forms import FORM_A, FORM_B  # noqa: E402

OUT = ROOT / "docs" / "evidence" / "pilot_results.md"
FORMS = {"A": FORM_A, "B": FORM_B}
NAMES = {
    "C1": "Place value",
    "C2": "Adding with carrying",
    "C3": "Taking away with borrowing",
}
KIND = {"pre": "Pre-test", "post": "Post-test", "termly": "Termly check"}
HEAD = (
    "# Pilot results: before and after, by competency\n\n"
    "Generated by `scripts/pilot_results.py`. Do not edit by hand.\n\n"
)


def label(c: dict[str, Any]) -> str:
    kind = KIND.get(c.get("kind") or "pre", "Check")
    return f"{kind} Form {c['formKey']} ({c.get('checkDate') or 'no date'})"


def choose(
    checks: list[dict[str, Any]], pre_id: str | None, post_id: str | None
) -> tuple[dict[str, Any], dict[str, Any]] | None:
    by_id = {c["id"]: c for c in checks}
    if pre_id and post_id:
        return by_id[pre_id], by_id[post_id]
    order = sorted(checks, key=lambda c: (c.get("checkDate") or "", c.get("updatedAt", 0)))
    pres = [c for c in order if (c.get("kind") or "pre") == "pre"]
    if not pres:
        return None
    pre = pres[-1]
    posts = [c for c in order if c.get("kind") == "post" and order.index(c) > order.index(pre)]
    return (pre, posts[0]) if posts else None


def render(pre: dict[str, Any], post: dict[str, Any], p: Pairing, simulated: bool) -> str:
    left_out = p.excluded_absent + p.excluded_not_entered + p.excluded_unmatched
    lines = [
        HEAD,
        f"**{label(pre)} to {label(post)}.** A small pilot"
        + (", on simulated data" if simulated else "")
        + f": {p.paired} children paired by roll order; {left_out} left out "
        f"({p.excluded_absent} away, {p.excluded_not_entered} with nothing entered, "
        f"{p.excluded_unmatched} with no partner).",
        "",
    ]
    if p.small_sample:
        lines += ["Fewer than 10 children are paired: read this as directional only.", ""]
    lines += [
        "| Competency | Flagged before | No longer flagged | Still flagged | Newly flagged |",
        "| --- | --- | --- | --- | --- |",
    ]
    for name in COMPETENCIES:
        ch = p.by_competency[name]
        cells = [ch.flagged_before, ch.fixed, ch.still_flagged, ch.newly_flagged]
        lines.append(f"| {name} {NAMES[name]} | " + " | ".join(map(str, cells)) + " |")
    lines += [
        "",
        "Counts of children. A change here is not yet a verdict: the verdict compares the "
        "trained error with the untrained ones (`engine/evaluation.py`), and it judges the "
        "track, never the teacher.",
        "",
    ]
    return "\n".join(lines)


def awaiting() -> str:
    return (
        HEAD + "**No pre-test and post-test pair has been entered yet.** This page is written from "
        "a pair of checks of one class (a pre-test, then a post-test on the twin paper). Until "
        "a pilot class has both, there is nothing to report, and no number is shown.\n"
    )


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("backup", nargs="?")
    ap.add_argument("--class", dest="klass")
    ap.add_argument("--pre")
    ap.add_argument("--post")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    out = Path(a.out)
    if not a.backup:
        out.write_text(awaiting(), encoding="utf-8")
        print(f"wrote {out.name}: no pair yet")
        return 0
    data = json.loads(Path(a.backup).read_text(encoding="utf-8"))
    if data.get("sealed"):
        print("this backup is sealed: restore it in the app and export it unsealed here")
        return 2
    classes = {c["id"]: c for c in data.get("classes", [])}
    klass = a.klass or next(iter(classes), None)
    checks = [c for c in data.get("checks", []) if c.get("classId") == klass]
    pair = choose(checks, a.pre, a.post)
    if pair is None:
        out.write_text(awaiting(), encoding="utf-8")
        print(f"wrote {out.name}: this class has no pre-test and post-test pair")
        return 0
    pre, post = pair
    p = pair_checks(
        FORMS[pre["formKey"]],
        pre["children"],
        FORMS[post["formKey"]],
        post["children"],
        set(pre.get("absent") or []),
        set(post.get("absent") or []),
    )
    out.write_text(
        render(pre, post, p, bool(classes.get(klass or "", {}).get("simulated"))), encoding="utf-8"
    )
    print(f"wrote {out.name}: {p.paired} paired")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
