"""Extract the deck, slide by slide, into docs/submission/slides.md for the judge guide.

    python scripts/extract_deck.py           write slides.md
    python scripts/extract_deck.py --check   exit 1 if slides.md is out of date

Source, in order of preference:
1. docs/submission/deck.pptx (the final deck): each slide's title, its text and its speaker notes.
   Needs python-pptx (`pip install python-pptx`).
2. docs/submission/deck.md (the deck source, until the final deck exists). Sections marked
   "(two slides)" are split at their "Slide A:" and "Slide B:" parts, so the numbering follows the
   slides as they will be built. slides.md then says it is provisional.

Run it again once the final deck is in docs/submission/, then rebuild the assistant index.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUB = ROOT / "docs" / "submission"
OUT = SUB / "slides.md"

_SECTION = re.compile(r"^##\s+(\d+)\.\s+(.*?)\s*$")
_PART = re.compile(r"Slide ([A-Z]):\s*")


def from_markdown(text: str) -> list[tuple[str, str, str]]:
    """(title, text, notes) per slide from deck.md."""
    sections: list[tuple[str, list[str]]] = []
    for line in text.splitlines():
        m = _SECTION.match(line)
        if m:
            sections.append((m.group(2), []))
        elif sections:
            sections[-1][1].append(line)
    slides: list[tuple[str, str, str]] = []
    for title, body_lines in sections:
        body = "\n".join(body_lines).strip()
        two = "(two slides)" in title
        clean = title.replace("(two slides)", "").strip()
        if two:
            parts = [p for p in _PART.split(body) if p.strip()]
            # split() gives [prefix?, "A", textA, "B", textB]: pair the letters with their text
            pairs: list[tuple[str, str]] = []
            i = 0
            while i < len(parts):
                if re.fullmatch(r"[A-Z]", parts[i].strip()) and i + 1 < len(parts):
                    pairs.append((parts[i].strip(), parts[i + 1].strip()))
                    i += 2
                else:
                    i += 1
            for letter, part in pairs or [("A", body)]:
                slides.append((f"{clean} ({letter})", part, ""))
        else:
            slides.append((clean, body, ""))
    return slides


def from_pptx(path: Path) -> list[tuple[str, str, str]]:
    from pptx import Presentation  # type: ignore[import-not-found]

    out: list[tuple[str, str, str]] = []
    for slide in Presentation(str(path)).slides:
        title = slide.shapes.title.text.strip() if slide.shapes.title is not None else ""
        texts = []
        for shape in slide.shapes:
            if shape == slide.shapes.title or not getattr(shape, "has_text_frame", False):
                continue
            t = shape.text_frame.text.strip()
            if t:
                texts.append(t)
        notes = slide.notes_slide.notes_text_frame.text.strip() if slide.has_notes_slide else ""
        out.append(
            (title or (texts[0].splitlines()[0] if texts else "Untitled"), "\n".join(texts), notes)
        )
    return out


def render(slides: list[tuple[str, str, str]], source: str, provisional: bool) -> str:
    head = [
        "# Deck, slide by slide",
        "",
        f"Generated by `python scripts/extract_deck.py` from `{source}`; do not edit by hand.",
    ]
    if provisional:
        head.append(
            "PROVISIONAL: built from the deck source because `docs/submission/deck.pptx` is not in the "
            "repository yet. Slide numbers follow the planned order; run the script again on the final deck."
        )
    lines = head + [""]
    for n, (title, text, notes) in enumerate(slides, 1):
        lines += [f"## Slide {n}: {title}", "", text.strip()]
        if notes:
            lines += ["", f"Speaker notes: {notes.strip()}"]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def build() -> str:
    pptx = SUB / "deck.pptx"
    if pptx.exists():
        try:
            return render(from_pptx(pptx), "docs/submission/deck.pptx", provisional=False)
        except ImportError:
            print(
                "deck.pptx found but python-pptx is not installed; using deck.md", file=sys.stderr
            )
    return render(
        from_markdown((SUB / "deck.md").read_text(encoding="utf-8")),
        "docs/submission/deck.md",
        provisional=True,
    )


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        ok = OUT.exists() and OUT.read_text(encoding="utf-8") == text
        print(
            "slides.md is current"
            if ok
            else "slides.md is OUT OF DATE: run python scripts/extract_deck.py"
        )
        return 0 if ok else 1
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count(chr(10) + '## Slide ')} slides")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
