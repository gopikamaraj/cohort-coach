def _expected_stage(r: Any) -> dict[str, Any]:
    return {
        "signatures": sorted(r.signatures),
        "signature_stages": sorted([c, s.value] for c, s in r.signature_stages),
        "stages": sorted(s.value for s in r.stages),
        "not_attempted": r.not_attempted,
        "anchor_wrong": r.anchor_wrong,
        "no_method_possible": r.no_method_possible,
        "no_method_confirmed": r.no_method_confirmed,
        "missed_teaching": r.missed_teaching,
        "missed_concepts": sorted(r.missed_concepts),
        "excluded": sorted(r.excluded),
    }


def _stage_result(form_key: str, raw: list[str], tags: dict[str, Any]) -> Any:
    return classify_child(
        PILOT_FORMS[form_key],
        _readings(raw),
        missed_teaching=bool(tags.get("missed")),
        missed_concepts=tags.get("missed_concepts", ()),
        unreadable=int(tags.get("unreadable", 0)),
        two_answers=int(tags.get("two_answers", 0)),
    )


def _expected_counts(results: list[Any]) -> dict[str, Any]:
    c = class_counts(results)
    return {
        "checked": c.checked,
        "missed_teaching": c.missed_teaching,
        "missed_by_concept": c.missed_by_concept,
        "not_attempted": c.not_attempted,
        "by_signature": sorted([code, s.value, n] for (code, s), n in c.by_signature.items()),
        "by_stage": sorted([s.value, n] for s, n in c.by_stage.items()),
    }


def build_stage_cases() -> dict[str, Any]:
    rng = random.Random(CASES_SEED + 1)
    children: list[dict[str, Any]] = []
    for name, form_key, raw, tags in _STAGE_NAMED:
        children.append({"name": name, "form": form_key, "raw": raw, "tags": tags})
    for i in range(120):
        form_key = "A" if i % 3 else "B"
        children.append(
            {
                "name": f"random_{i:03d}",
                "form": form_key,
                "raw": _random_child_on(PILOT_FORMS[form_key], rng),
                "tags": {
                    "missed": rng.random() < 0.05,
                    "missed_concepts": [c for c in CONCEPTS if rng.random() < 0.15],
                    "unreadable": rng.choice([0, 0, 0, 1, 2]),
                },
            }
        )
    for c in children:
        c["expected"] = _expected_stage(_stage_result(c["form"], c["raw"], c["tags"]))
    classes: list[dict[str, Any]] = []
    for size in (1, 8, 20, 30):
        rows = children[:size]
        classes.append(
            {
                "name": f"class_of_{size}",
                "children": [
                    {"form": r["form"], "raw": r["raw"], "tags": r["tags"]}
                    for r in rows
                    if r["form"] == "A"
                ],
                "expected": _expected_counts(
                    [_stage_result("A", r["raw"], r["tags"]) for r in rows if r["form"] == "A"]
                ),
            }
        )
    return {
        "_about": "Synthetic stage cases (seed 2027), generated by engine/export_keys.py. "
        "No real child. Do not edit by hand; run `python tasks.py export-keys`.",
        "children": children,
        "classes": classes,
    }


def _random_child_on(form: Form, rng: random.Random) -> list[str]:
    """Raw answers on a form: correct, a known error, a signature answer, junk or blank."""
    out: list[str] = []
    for item in form.items:
        roll = rng.random()
        sigs = sorted(a for answers in signature_answers(item).values() for a in answers)
        if roll < 0.4:
            out.append(str(correct_answer(item)))
        elif roll < 0.7 and sigs:
            out.append(str(rng.choice(sigs)))
        elif roll < 0.85:
            out.append(str(rng.randint(1, 999)))
        elif roll < 0.93:
            out.append("")
        else:
            out.append(rng.choice(["?", "x", "3 4"]))
    return out
