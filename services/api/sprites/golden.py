"""The parity cases: Python renders each, the TypeScript renderer must give the same bytes.

`tests/fixtures/sprite_golden.json` holds the SHA-256 and length of each SVG (written by
`scripts/export_keys.py`); `apps/pwa/src/sprites/golden.test.ts` renders the same cases and
compares. A case is plain data so both sides read it identically.
"""

from __future__ import annotations

import hashlib
from typing import Any

from services.api.sprites.avatar import avatar_svg, expression_ids, persona_look, personas, seat_row
from services.api.sprites.palette import palette
from services.api.sprites.scene import render_layout


def cases() -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    for item in ("ball", "stick", "mango"):
        for n in (0, 1, 9, 10, 23, 45, 100):
            out.append({"fn": "row", "item": item, "args": {"n": n}, "seed": 1})
            out.append({"fn": "scatter", "item": item, "args": {"n": n}, "seed": 7})
            out.append({"fn": "bundle_group", "item": item, "args": {"n": n}, "seed": 1})
    for n in (0, 7, 10, 17, 20):
        out.append({"fn": "ten_frame", "item": "counter", "args": {"n": n}, "seed": 1})
    for n in (0, 5, 47, 99):
        out.append({"fn": "place_value_mat", "item": "stick", "args": {"n": n}, "seed": 1})
    for r, c in ((1, 1), (3, 4), (10, 10)):
        out.append({"fn": "grid_array", "item": "pencil", "args": {"r": r, "c": c}, "seed": 1})
    for total, marked in ((10, 3), (52, 29), (100, 100)):
        out.append(
            {
                "fn": "cross_out",
                "item": "ball",
                "args": {"total": total, "marked": marked},
                "seed": 1,
            }
        )
    for a, b in ((0, 0), (23, 45), (100, 100)):
        out.append({"fn": "two_groups", "item": "mango", "args": {"a": a, "b": b}, "seed": 3})
    out.append(
        {
            "fn": "number_line",
            "item": None,
            "args": {"min": 0, "max": 100, "marks": [3, 50, 99]},
            "seed": 1,
        }
    )
    out.append(
        {
            "fn": "number_line",
            "item": None,
            "args": {"min": 30, "max": 40, "marks": [31]},
            "seed": 1,
        }
    )
    out.append({"fn": "bar_model", "item": None, "args": {"parts": [3, 5, 2]}, "seed": 1})
    for pal in ("warm", "cool", "high_contrast"):
        out.append({"fn": "scatter", "item": "ball", "args": {"n": 12}, "seed": 2, "palette": pal})
    for pid in personas():
        out.append({"fn": "avatar", "persona": pid, "expression": "neutral", "mouth": "closed"})
    for expr in expression_ids():
        for mouth in ("closed", "open"):
            out.append({"fn": "avatar", "persona": "meena", "expression": expr, "mouth": mouth})
    out.append(
        {
            "fn": "seat_row",
            "children": [
                {"persona": p, "expression": e, "speaking": i == 1}
                for i, (p, e) in enumerate(
                    [
                        ("meena", "neutral"),
                        ("ravi", "got_it"),
                        ("asha", "confused"),
                        ("vijay", "shy"),
                        ("nila", "thinking"),
                    ]
                )
            ],
        }  # fmt: skip
    )
    return out


def render_case(case: dict[str, Any]) -> str:
    fn = case["fn"]
    if fn == "avatar":
        return avatar_svg(persona_look(case["persona"])["look"], case["expression"], case["mouth"])
    if fn == "seat_row":
        kids = [
            {
                "look": persona_look(c["persona"])["look"],
                "expression": c["expression"],
                "speaking": c["speaking"],
            }
            for c in case["children"]
        ]
        return seat_row(kids)
    pal = palette(case.get("palette", "default"))
    return render_layout(fn, case.get("item"), case["args"], pal, case.get("seed", 0)).svg


def golden() -> dict[str, Any]:
    out = []
    for case in cases():
        svg = render_case(case)
        out.append(
            {
                "case": case,
                "sha256": hashlib.sha256(svg.encode("utf-8")).hexdigest(),
                "length": len(svg),
            }
        )
    return {
        "_about": "Parity cases for the sprite renderers (Python writes, TypeScript must match). "
        "Generated by scripts/export_keys.py; do not edit by hand.",
        "cases": out,
    }
